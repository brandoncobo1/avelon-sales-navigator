import type { Branch, BranchType, CallOutcome, ObjectionClassification, ObjectionType, Speaker } from "@/lib/types";
import { deriveCategory } from "@/lib/branch-category";

// The full Script 1 (receptionist) conversation tree, plus a full
// decision-maker tree the receptionist path transfers/routes into.
//
// This is structured data, not UI copy — it is seeded into the Branch table
// and from then on is editable entirely through the Conversation Builder
// without touching code. IDs are stable, human-readable strings so branches
// can safely reference each other (a branch may be reached from more than
// one parent — this is a DAG, not a strict tree — e.g. every "who's the
// decision-maker" moment converges on `sw-f-speak-to-manager`).

export type SeedBranch = Omit<Branch, "createdAt" | "updatedAt" | "terminal"> & { id: string };

let orderCounter = 0;
function next() {
  orderCounter += 1;
  return orderCounter;
}

function b(partial: {
  id: string;
  title: string;
  speaker: Speaker;
  type: BranchType;
  stage: string;
  category?: string;
  trigger: string;
  responseText: string;
  responseAlt?: string;
  objective: string;
  notes?: string;
  warning?: string;
  tags?: string[];
  aiKeywords?: string[];
  nextBranchIds?: string[];
  previousBranchId?: string;
  isRoot?: boolean;
  outcome?: CallOutcome;
  objectionType?: ObjectionType;
  classification?: ObjectionClassification;
  whyItWorks?: string;
  aiConfidenceThreshold?: number;
  branchPriority?: number;
  abTestGroup?: string;
}): SeedBranch {
  return {
    id: partial.id,
    title: partial.title,
    speaker: partial.speaker,
    type: partial.type,
    stage: partial.stage,
    category: partial.category ?? deriveCategory(partial.stage),
    trigger: partial.trigger,
    responseText: partial.responseText,
    responseAlt: partial.responseAlt ?? null,
    objective: partial.objective,
    notes: partial.notes ?? null,
    warning: partial.warning ?? null,
    tags: partial.tags ?? [],
    aiKeywords: partial.aiKeywords ?? [],
    nextBranchIds: partial.nextBranchIds ?? [],
    previousBranchId: partial.previousBranchId ?? null,
    order: next(),
    isRoot: partial.isRoot ?? false,
    outcome: partial.outcome ?? null,
    objectionType: partial.objectionType ?? null,
    classification: partial.classification ?? null,
    whyItWorks: partial.whyItWorks ?? null,
    aiConfidenceThreshold: partial.aiConfidenceThreshold ?? null,
    branchPriority: partial.branchPriority ?? 0,
    abTestGroup: partial.abTestGroup ?? null,
  };
}

