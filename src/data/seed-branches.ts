function finalizeBranches(branches: SeedBranch[]): SeedBranch[] {
  return branches.map((branch) => ({
    ...branch,
    objectionType: OBJECTION_TYPE_BY_ID[branch.id] ?? branch.objectionType,
    outcome: OUTCOME_BY_ID[branch.id] ?? branch.outcome,
    classification: CLASSIFICATION_BY_ID[branch.id] ?? branch.classification,
    // Every objection is a valid "any moment" entry point, reachable via the
    // Objections search panel ('O') regardless of where it sits in the
    // graph — not just the handful surfaced on the always-visible quick
    // bar. This is what "objections can happen at any moment" means
    // structurally: it's not one hardcoded list, it's every objection.
    isRoot: branch.type === "OBJECTION" ? true : branch.isRoot,
  }));
}

